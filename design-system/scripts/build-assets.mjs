// Builds icons and logos from the Figma exports, then bundles all CSS into one file.
//
//   npm run build:assets   (part of npm run build)
//
// Input:  tokens/figma-export/icons.json, tokens/figma-export/logos.json, dist/css/*.css
// Output: dist/icons/*.svg, dist/icons/sprite.svg, dist/json/icons.json,
//         dist/logos/*.svg, dist/css/icons.css, dist/css/scalenut.css (foundations + components)

import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';

const read = (p) => JSON.parse(readFileSync(p, 'utf8'));
const out = (p, s) => {
  mkdirSync(p.split('/').slice(0, -1).join('/'), { recursive: true });
  writeFileSync(p, s);
};

// ─── Icons ──────────────────────────────────────────────────────────────────
const { icons, viewBox } = read('tokens/figma-export/icons.json');
const paths = (packed) =>
  packed.split('|').map((p) => (p.startsWith('!') ? { d: p.slice(1), evenodd: true } : { d: p, evenodd: false }));
const pathTags = (packed) =>
  paths(packed)
    .map(({ d, evenodd }) => (evenodd ? `<path fill-rule="evenodd" clip-rule="evenodd" d="${d}"/>` : `<path d="${d}"/>`))
    .join('');

rmSync('dist/icons', { recursive: true, force: true });
const names = Object.keys(icons).sort();
for (const name of names) {
  out(
    `dist/icons/${name}.svg`,
    `<svg xmlns="http://www.w3.org/2000/svg" width="${viewBox}" height="${viewBox}" viewBox="0 0 ${viewBox} ${viewBox}" fill="currentColor" aria-hidden="true">${pathTags(icons[name])}</svg>\n`,
  );
}
out(
  'dist/icons/sprite.svg',
  `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n${names
    .map((n) => `  <symbol id="icon-${n}" viewBox="0 0 ${viewBox} ${viewBox}" fill="currentColor">${pathTags(icons[n])}</symbol>`)
    .join('\n')}\n</svg>\n`,
);
out('dist/json/icons.json', JSON.stringify(names.map((n) => ({ name: n, paths: paths(icons[n]) })), null, 2) + '\n');

out(
  'dist/css/icons.css',
  `/**
 * Icon sizing and colour. Generated, do not edit by hand.
 * Markup: <svg class="icon"><use href="/icons/sprite.svg#icon-search"/></svg>, or paste an SVG from dist/icons/.
 * Icons fill with currentColor, so they take the text colour of their parent unless you set one.
 */

.icon {
  display: inline-block;
  flex-shrink: 0;
  width: var(--size-icon-sm);
  height: var(--size-icon-sm);
  color: var(--icon-primary);
  fill: currentColor;
  vertical-align: middle;
}
.icon--xs { width: var(--size-icon-xs); height: var(--size-icon-xs); }
.icon--sm { width: var(--size-icon-sm); height: var(--size-icon-sm); }
.icon--md { width: var(--size-icon-md); height: var(--size-icon-md); }
.icon--lg { width: var(--size-icon-lg); height: var(--size-icon-lg); }
.icon--secondary { color: var(--icon-secondary); }
.icon--brand { color: var(--icon-brand); }
.icon--on-brand { color: var(--icon-on-brand); }
.icon--disabled { color: var(--icon-disabled); }
.icon--error { color: var(--icon-error); }
.icon--success { color: var(--icon-success); }
.icon--warning { color: var(--icon-warning); }
.icon--ai { color: var(--icon-ai); }
.icon--inherit { color: inherit; }
`,
);

// ─── Logos ──────────────────────────────────────────────────────────────────
const { mark, logo } = read('tokens/figma-export/logos.json');
const markShapes = mark.shapes.map((s) => `<path fill="${s.fill}" d="${s.d}"/>`).join('');
const svg = (w, h, vb, body, title) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="${vb}" role="img" aria-label="${title}"><title>${title}</title>${body}</svg>\n`;

rmSync('dist/logos', { recursive: true, force: true });
out('dist/logos/scalenut-mark.svg', svg(48, 48, `0 0 ${mark.viewBox} ${mark.viewBox}`, markShapes, 'Scalenut'));
out('dist/logos/scalenut-favicon.svg', svg(32, 32, `0 0 ${mark.viewBox} ${mark.viewBox}`, markShapes, 'Scalenut'));
const scale = logo.markSize / mark.viewBox;
const fullLogo = (fill) =>
  `<g transform="scale(${+scale.toFixed(6)})">${markShapes}</g><path fill="${fill}" d="${logo.wordmark.d}"/>`;
const vb = `0 0 ${logo.width} ${logo.height}`;
out('dist/logos/scalenut-logo.svg', svg(logo.width, logo.height, vb, fullLogo(logo.wordmark.fillLight), 'Scalenut'));
out('dist/logos/scalenut-logo-on-dark.svg', svg(logo.width, logo.height, vb, fullLogo(logo.wordmark.fillDark), 'Scalenut'));

// ─── Bundle ─────────────────────────────────────────────────────────────────
const parts = ['colors', 'typography', 'spacing', 'effects', 'gradients', 'icons', 'button',
  'badge', 'checkbox', 'toggle', 'input', 'radio', 'avatar', 'tag', 'tooltip', 'spinner', 'divider', 'select'];
out(
  'dist/css/scalenut.css',
  `/**
 * Scalenut Design System: every foundation in one file.
 * Generated by npm run build from ${parts.map((p) => `${p}.css`).join(', ')}. Do not edit by hand.
 */\n\n` + parts.map((p) => `/* ── ${p}.css ── */\n${readFileSync(`dist/css/${p}.css`, 'utf8')}`).join('\n'),
);

console.log(`✓ ${names.length} icons, 4 logo files, scalenut.css bundle`);
